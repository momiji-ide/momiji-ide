#!/usr/bin/env node
/**
 * Patches node-pty's winpty.gyp to skip GetCommitHash.bat
 * which fails on CI due to path issues.
 * Also creates gen/GenVersion.h manually.
 *
 * Run: node scripts/patch-node-pty.js
 */

const fs   = require('fs')
const path = require('path')

const gypPath    = path.join(__dirname, '..', 'node_modules', 'node-pty', 'deps', 'winpty', 'src', 'winpty.gyp')
const genDir     = path.join(__dirname, '..', 'node_modules', 'node-pty', 'deps', 'winpty', 'src', 'gen')
const headerPath = path.join(genDir, 'GenVersion.h')

if (!fs.existsSync(gypPath)) {
  console.log('[patch-node-pty] winpty.gyp not found — skipping (not Windows or node-pty not installed)')
  process.exit(0)
}

// Read and patch winpty.gyp
let gyp = fs.readFileSync(gypPath, 'utf-8')

// Replace GetCommitHash.bat call with hardcoded value
gyp = gyp.replace(
  /<!\(cmd \/c "cd shared && GetCommitHash\.bat"\)/g,
  'none'
)

// Replace UpdateGenVersion.bat call with static include dir
gyp = gyp.replace(
  /<!\(cmd \/c "cd shared && UpdateGenVersion\.bat <\(WINPTY_COMMIT_HASH\)"\)/g,
  'gen'
)

fs.writeFileSync(gypPath, gyp, 'utf-8')
console.log('[patch-node-pty] Patched winpty.gyp ✓')

// Create gen/GenVersion.h
if (!fs.existsSync(genDir)) {
  fs.mkdirSync(genDir, { recursive: true })
}

fs.writeFileSync(headerPath, [
  '// AUTO-GENERATED by scripts/patch-node-pty.js',
  'const char GenVersion_Version[] = "0.4.4-dev";',
  'const char GenVersion_Commit[] = "none";',
  ''
].join('\n'), 'utf-8')

console.log('[patch-node-pty] Created gen/GenVersion.h ✓')
console.log('[patch-node-pty] Done!')
